<?php

namespace App\Nbs;

/**
 * Srpska ćirilica u latinicu (NBS ponekad vraća naziv, adresu ili mesto na ćirilici).
 */
final class Transliterator
{
    private const MAP = [
        'Љ' => 'Lj', 'Њ' => 'Nj', 'Џ' => 'Dž', 'љ' => 'lj', 'њ' => 'nj', 'џ' => 'dž',
        'А' => 'A', 'Б' => 'B', 'В' => 'V', 'Г' => 'G', 'Д' => 'D', 'Ђ' => 'Đ', 'Е' => 'E', 'Ж' => 'Ž', 'З' => 'Z', 'И' => 'I',
        'Ј' => 'J', 'К' => 'K', 'Л' => 'L', 'М' => 'M', 'Н' => 'N', 'О' => 'O', 'П' => 'P', 'Р' => 'R', 'С' => 'S', 'Т' => 'T',
        'Ћ' => 'Ć', 'У' => 'U', 'Ф' => 'F', 'Х' => 'H', 'Ц' => 'C', 'Ч' => 'Č', 'Ш' => 'Š',
        'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'ђ' => 'đ', 'е' => 'e', 'ж' => 'ž', 'з' => 'z', 'и' => 'i',
        'ј' => 'j', 'к' => 'k', 'л' => 'l', 'м' => 'm', 'н' => 'n', 'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't',
        'ћ' => 'ć', 'у' => 'u', 'ф' => 'f', 'х' => 'h', 'ц' => 'c', 'ч' => 'č', 'ш' => 'š',
    ];

    public static function toLatin(string $text): string
    {
        $latin = strtr($text, self::MAP);

        // "ЉУБА" -> "LjUBA" bi bilo ružno: u reči pisanoj velikim slovima i digraf ide velikim slovima
        return preg_replace_callback('/(Lj|Nj|Dž)(?=\p{Lu})|(?<=\p{Lu})(Lj|Nj|Dž)(?!\p{Ll})/u', static fn (array $m) => mb_strtoupper($m[0]), $latin) ?? $latin;
    }
}
